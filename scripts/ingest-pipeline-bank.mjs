// ingest-pipeline-bank.mjs — publish the question bank's import-ready, public rows to the site.
//
// Input: data/MCQS_FINAL/by_status/ready.json (written by data/MCQS/_pipeline/build_final.mjs).
// Output: lib/pipeline-bank.ts, merged with the other banks in lib/topicals.ts.
//
// HONESTY RULES
//   * Only `ready` rows: a stem, four distinct options and exactly one printed key (A-D). Rows that
//     need a key, an option or a figure are not published.
//   * Only `visibility: public` rows. The bank marks academy-book compilations `private` precisely so
//     they are never re-hosted; publishing those would break the board's rule.
//   * Every row keeps the source label of the corpus it came from. Nothing is presented as an
//     official paper we did not verify.
//
// usage: node scripts/ingest-pipeline-bank.mjs

import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(import.meta.dirname, '..');
const IN = path.join(ROOT, 'data/MCQS_FINAL/by_status/ready.json');
const OUT = path.join(ROOT, 'lib/pipeline-bank.ts');

if (!fs.existsSync(IN)) {
  console.error('missing', IN, '— run data/MCQS/_pipeline/build_final.mjs first');
  process.exit(1);
}

const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
function hash8(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}

// Already published: never add the same question twice.
const onSite = new Set();
for (const f of ['lib/topicals-bank.ts', 'lib/founder-bank.ts']) {
  const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
  for (const m of src.matchAll(/question_text:\s*'((?:[^'\\]|\\.)*)'/g)) onSite.add(norm(m[1].replace(/\\'/g, "'")));
}

const ready = JSON.parse(fs.readFileSync(IN, 'utf8')).questions;
const publicReady = ready.filter((r) => r.visibility === 'public');
const subjects = new Set(['Biology', 'Chemistry', 'Physics', 'English']);

const rows = [];
const skipped = { notPublic: ready.length - publicReady.length, subject: 0, duplicate: 0, badKey: 0 };
const seen = new Set();
for (const r of publicReady) {
  if (!subjects.has(r.subject)) { skipped.subject += 1; continue; }
  if (!['A', 'B', 'C', 'D'].includes(r.correct_answer)) { skipped.badKey += 1; continue; }
  if (!r.option_a || !r.option_b || !r.option_c || !r.option_d) { skipped.badKey += 1; continue; }
  const k = norm(r.question_text);
  if (onSite.has(k) || seen.has(k)) { skipped.duplicate += 1; continue; }
  seen.add(k);
  rows.push({
    id: `pipe-${hash8(r.subject + '|' + r.question_text)}`,
    subject: r.subject,
    chapter: r.chapter && r.chapter !== 'Unplaced' ? r.chapter : 'Mixed Bank',
    question_text: r.question_text,
    option_a: r.option_a,
    option_b: r.option_b,
    option_c: r.option_c,
    option_d: r.option_d,
    correct_answer: r.correct_answer,
    source: r.past_paper_sources && r.past_paper_sources.length
      ? 'Question bank — past-paper provenance'
      : 'Question bank — keyed collection',
  });
}

const body = rows
  .map(
    (r) => `  {
    key: ${q(r.id)},
    subject: ${q(r.subject)},
    chapter: ${q(r.chapter)},
    question_text: ${q(r.question_text)},
    option_a: ${q(r.option_a)},
    option_b: ${q(r.option_b)},
    option_c: ${q(r.option_c)},
    option_d: ${q(r.option_d)},
    correct_answer: ${q(r.correct_answer)},
    source: ${q(r.source)},
  },`,
  )
  .join('\n');

fs.writeFileSync(
  OUT,
  `// PIPELINE BANK — import-ready, public rows from the question bank, ingested ${new Date().toISOString().slice(0, 10)}.
//
// OWNERSHIP: generated by \`node scripts/ingest-pipeline-bank.mjs\` from
// data/MCQS_FINAL/by_status/ready.json; hand edits are overwritten. Merged into the pages by
// lib/topicals.ts.
//
// HONESTY: only rows with a stem, four distinct options and a key printed in the source are here,
// and only rows the bank marks \`public\` — academy-book compilations stay private and unpublished.

import type { TopicalsQuestion } from './topicals-bank';

export const PIPELINE_BANK: TopicalsQuestion[] = [
${body}
];
`,
);

const byChapter = {};
for (const r of rows) {
  const k = `${r.subject} / ${r.chapter}`;
  byChapter[k] = (byChapter[k] || 0) + 1;
}
console.log('written', path.relative(ROOT, OUT));
console.log('published', rows.length, '| skipped', JSON.stringify(skipped));
console.log(JSON.stringify(byChapter, null, 1));

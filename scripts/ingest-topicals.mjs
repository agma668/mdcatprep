// One-shot ingest: converts the founder's extracted MCQ bank
// (Downloads/TODO/mdcat-extracted-qs/mdcat_question_bank.json) into
// lib/topicals-bank.ts.
//
//   node scripts/ingest-topicals.mjs
//
// Rules encoded here (match the board's honesty/copyright rules):
//  - KIPS / Prep Titans / CATPrep / Medquack material is NEVER ingested. This
//    script reads ONLY the mcquniverse-derived bank the founder extracted.
//  - Only 4-option MCQs render (the option grid is A–D); short-answer and
//    2/3-option rows are skipped, and the skip counts are printed.
//  - Dedup by normalized question text (same text appearing across chapter
//    files must not render twice).
//  - The answer is stored as the option LETTER after shuffle-free mapping;
//    option order from the source is preserved (the player shuffles at
//    render time, not in the data).
//  - Source is stated honestly on every question: 'MCQ Universe (founder
//    extraction)' — never relabelled as original exam-style writing.

import { readFileSync, writeFileSync } from "node:fs";

const SRC = String.raw`C:\Users\admin\Downloads\TODO\mdcat-extracted-qs\mdcat_question_bank.json`;
const OUT = new URL("../lib/topicals-bank.ts", import.meta.url);

const bank = JSON.parse(readFileSync(SRC, "utf8"));

const SUBJECT_LABEL = {
  Biology: "Biology",
  Chemistry: "Chemistry",
  Physics: "Physics",
  English: "English",
};

const LETTERS = ["A", "B", "C", "D"];

const esc = (s) =>
  String(s)
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "\\'")
    .replace(/\r?\n/g, " ")
    .trim();

const normKey = (s) =>
  String(s).toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();

// chapter slugs like "acellular-life-mcqs" → "Acellular Life"
const chapterTitle = (slug) =>
  String(slug || "General")
    .replace(/-mcqs$/i, "")
    .split("-")
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(" ");

const seen = new Set();
const out = [];
let skippedFormat = 0;
let skippedOptions = 0;
let skippedDupe = 0;
let skippedBadAnswer = 0;

for (const q of bank) {
  if ((q.format ?? "mcq") !== "mcq") { skippedFormat++; continue; }
  const opts = Array.isArray(q.options) ? q.options.map((o) => String(o ?? "").trim()) : [];
  if (opts.length !== 4 || opts.some((o) => !o)) { skippedOptions++; continue; }
  const answerIdx = opts.findIndex((o) => normKey(o) === normKey(q.answer ?? ""));
  if (answerIdx < 0) { skippedBadAnswer++; continue; }
  const text = String(q.q ?? "").trim();
  if (text.length < 8) { skippedBadAnswer++; continue; }
  const key = normKey(text);
  if (seen.has(key)) { skippedDupe++; continue; }
  seen.add(key);

  out.push({
    key: `top-${out.length + 1}`,
    subject: SUBJECT_LABEL[q.subject] ?? q.subject,
    chapter: chapterTitle(q.chapter),
    question_text: text,
    options: opts,
    correct_answer: LETTERS[answerIdx],
    source: String(q.source ?? "mcquniverse.pk"),
  });
}

// Group stats the hub pages can recompute — printed once here for the log.
const bySubject = {};
const byChapter = {};
for (const q of out) {
  bySubject[q.subject] = (bySubject[q.subject] ?? 0) + 1;
  byChapter[`${q.subject} :: ${q.chapter}`] = (byChapter[`${q.subject} :: ${q.chapter}`] ?? 0) + 1;
}

const header = `// TOPICALS BANK — chapter-wise MCQs ingested from the founder's own
// extracted question bank (source: mcquniverse.pk extraction, run ${new Date().toISOString().slice(0, 10)}).
//
// OWNERSHIP: this file is generated by \`node scripts/ingest-topicals.mjs\`;
// hand edits will be overwritten on the next run. The seams live in
// lib/topicals.ts.
//
// HONESTY: every question carries source: 'MCQ Universe (founder extraction)'.
// Nothing here is presented as original MED Prep writing, and no question
// claims a past-paper year — none of these came from a real sitting.
// COMMERCIAL COMPILATIONS (KIPS / Prep Titans / CATPrep / Medquack) are
// deliberately absent — the board forbids re-hosting them.

export type TopicalsQuestion = {
  key: string;
  subject: string;
  chapter: string;
  question_text: string;
  option_a: string;
  option_b: string;
  option_c: string;
  option_d: string;
  correct_answer: "A" | "B" | "C" | "D";
  source: string;
};

export const TOPICALS_BANK: TopicalsQuestion[] = [
`;

const rows = out
  .map((q) => `  {
    key: '${q.key}',
    subject: '${esc(q.subject)}',
    chapter: '${esc(q.chapter)}',
    question_text: '${esc(q.question_text)}',
    option_a: '${esc(q.options[0])}',
    option_b: '${esc(q.options[1])}',
    option_c: '${esc(q.options[2])}',
    option_d: '${esc(q.options[3])}',
    correct_answer: '${q.correct_answer}',
    source: 'MCQ Universe (founder extraction)',
  },`)
  .join("\n");

writeFileSync(OUT, `${header}${rows}\n];\n`, "utf8");

console.log(`ingested: ${out.length}`);
console.log(`skipped: format=${skippedFormat} options=${skippedOptions} answer=${skippedBadAnswer} dupe=${skippedDupe}`);
console.log("bySubject:", JSON.stringify(bySubject));
const chapters = Object.entries(byChapter).sort((a, b) => b[1] - a[1]);
console.log(`chapters: ${chapters.length}`);
for (const [k, v] of chapters.slice(0, 12)) console.log(`  ${k}: ${v}`);

"""Generate MED Prep MDCAT question banks (biology/chemistry/physics/english)
and mcat master notes. Original content written for this site from the PMDC
MDCAT syllabus and public exam-pattern sources. Keys are deterministic uuid5.

usage: python scripts/generate-mdcat.py
Writes lib/{subject}-questions.ts and lib/mcat-notes.ts
"""
import uuid, os

NS = uuid.uuid5(uuid.NAMESPACE_URL, 'https://medprep.pk')

def key(seed: str) -> str:
    return str(uuid.uuid5(NS, seed))

def q(subject, topic, question_text, option_a, option_b, option_c, option_d,
      correct_answer, explanation, difficulty, seed):
    return {
        'key': key(seed),
        'subject': subject,
        'topic': topic,
        'question_text': question_text,
        'option_a': option_a,
        'option_b': option_b,
        'option_c': option_c,
        'option_d': option_d,
        'correct_answer': correct_answer,
        'explanation': explanation,
        'difficulty': difficulty,
        'source': 'PMDC MDCAT Exam Style',
    }

def ts_val(k, v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if k in ('difficulty', 'correct_answer'):
        return repr(v)
    return repr(str(v))

def render_questions(export_name, questions, intro, subj, out_path):
    lines = [
        intro,
        '',
        f"// Same shape as lib/resources.ts so the practice session renders it.",
        '',
        "export type ResourceQuestion = {",
        "  key: string",
        "  subject: string",
        "  topic: string",
        "  question_text: string",
        "  option_a: string",
        "  option_b: string",
        "  option_c: string",
        "  option_d: string",
        "  correct_answer: 'A' | 'B' | 'C' | 'D'",
        "  explanation: string",
        "  difficulty: 'easy' | 'medium' | 'hard'",
        "  source: string",
        "}",
        "",
        f"export const {export_name}: ResourceQuestion[] = [",
    ]
    for x in questions:
        lines.append('  {')
        for k, v in x.items():
            lines.append(f'    {k}: {ts_val(k, v)},')
        lines.append('  },')
    lines.append(']')
    lines.append('')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))


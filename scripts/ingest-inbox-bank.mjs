// ingest-inbox-bank.mjs — publish the founder's own inbox PDFs as site questions.
//
// Input: data/MCQS_INBOX/parsed/questions.json (written by
// data/MCQS_INBOX/_pipeline/inbox_parse.mjs from the PDFs in data/MCQS_INBOX/raw).
// Output: lib/founder-bank.ts, merged with the existing bank in lib/topicals.ts.
//
// HONESTY RULES
//   * Only a key printed in the source PDF is written. A question whose paper printed no key is
//     left out of the site bank rather than given a guessed answer; those rows stay in the inbox
//     file and are counted in the report.
//   * Every row says where it came from. Nothing claims an official sitting: the "Past Paper <year>"
//     label is the founder's own file name for the set, which is exactly how the existing bank
//     already treats those sets.
//   * No academy or university name appears in a row (the parser strips them).
//
// usage: node scripts/ingest-inbox-bank.mjs

import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(import.meta.dirname, '..');
const IN = path.join(ROOT, 'data/MCQS_INBOX/parsed/questions.json');
const OUT = path.join(ROOT, 'lib/founder-bank.ts');

if (!fs.existsSync(IN)) {
  console.error('missing', IN, '— run data/MCQS_INBOX/_pipeline/inbox_parse.mjs first');
  process.exit(1);
}

const rows = JSON.parse(fs.readFileSync(IN, 'utf8'));
// Rows from the rest of his MED material on the machine. Only the ones flagged publishable (not an
// academy compilation) and carrying a printed key go out.
const IN_E = path.join(ROOT, 'data/MCQS_INBOX/parsed/questions_e.json');
if (fs.existsSync(IN_E)) {
  for (const r of JSON.parse(fs.readFileSync(IN_E, 'utf8'))) if (r.publishable) rows.push(r);
}

// Stable id: the same stem always gets the same key, so re-running does not churn the diff.
function hash8(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

// Set labels come from file names, so they are tidied: duplicate segments collapsed, stray codes
// dropped, length capped. The name still describes the source file, nothing more.
function tidyLabel(chapter) {
  const parts = String(chapter)
    .split(/\s*[·|]\s*/)
    .map((p) => p.replace(/\.pdf$/i, '').replace(/\s{2,}/g, ' ').trim())
    .filter(Boolean)
    .filter((p) => !/^MDCAT\d*$/i.test(p) || p.toUpperCase() === 'MDCAT');
  const seen = new Set();
  const out = [];
  for (const p of parts) {
    const k = p.toLowerCase();
    if (seen.has(k)) continue;
    seen.add(k);
    out.push(p);
  }
  return (out.join(' · ') || 'Collection').slice(0, 48);
}

for (const r of rows) {
  if (!r.source || r.publishable === undefined) continue;
  const label = tidyLabel(r.chapter);
  // A file name that says nothing about the set ("Biologgy", "DOC · 20260917 · WA0021") is filed as
  // a mixed bank rather than shown to a student as if it were a named paper.
  r.chapter = /^(?:biolog\w*|chem\w*|physic\w*|DOC\b|WA\d{4})/i.test(label) ? 'Mixed Bank' : label;
}

const keyed = rows.filter((r) => r.correct_answer && ['A', 'B', 'C', 'D'].includes(r.correct_answer));
const skippedNoKey = rows.filter((r) => !r.correct_answer);

const seen = new Set();
const entries = [];
for (const r of keyed) {
  const id = `found-${hash8(r.subject + '|' + r.question_text)}`;
  if (seen.has(id)) continue;
  seen.add(id);
  const yearNote = /^Past Paper (\d{4})$/.exec(r.chapter);
  const source = yearNote
    ? `Founder bank — MDCAT past paper set, ${yearNote[1]}`
    : r.chapter === 'Mixed Bank'
      ? 'Founder bank — mixed past-paper compilation'
      : /mdcat|hec|nums|past|paper|test|mock|bumhs|usat|entry/i.test(r.chapter)
        ? `Founder bank — ${r.chapter}`
        : 'Founder bank — subject worksheet';
  entries.push({ id, r, source });
}

const body = entries
  .map(
    ({ id, r, source }) => `  {
    key: ${q(id)},
    subject: ${q(r.subject)},
    chapter: ${q(r.chapter)},
    question_text: ${q(r.question_text)},
    option_a: ${q(r.option_a)},
    option_b: ${q(r.option_b)},
    option_c: ${q(r.option_c)},
    option_d: ${q(r.option_d)},
    correct_answer: ${q(r.correct_answer)},
    source: ${q(source)},
  },`,
  )
  .join('\n');

const header = `// FOUNDER BANK — questions from the founder's own PDFs, ingested ${new Date().toISOString().slice(0, 10)}.
//
// OWNERSHIP: generated by \`node scripts/ingest-inbox-bank.mjs\` from
// data/MCQS_INBOX/parsed/questions.json; hand edits are overwritten. The seams live in lib/topicals.ts,
// which merges this bank with lib/topicals-bank.ts.
//
// HONESTY: every row carries a key that was printed in its source paper — a question whose paper
// printed no key was left out rather than guessed. \`source\` names the founder's own set; "Past
// Paper <year>" is that set's file name, not a verified official sitting.

import type { TopicalsQuestion } from './topicals-bank';

export const FOUNDER_BANK: TopicalsQuestion[] = [
${body}
];
`;

fs.writeFileSync(OUT, header);

const bySet = {};
for (const { r } of entries) {
  const k = r.subject + ' / ' + r.chapter;
  bySet[k] = (bySet[k] || 0) + 1;
}
console.log('written', path.relative(ROOT, OUT));
console.log('rows', entries.length, '| excluded for no printed key', skippedNoKey.length);
console.log(JSON.stringify(bySet, null, 1));
